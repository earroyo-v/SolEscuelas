CREATE DATABASE ELEKTRA

CREATE TABLE Escuelas(
	Id INT PRIMARY KEY IDENTITY(1,1),
	Nombre VARCHAR(50) NOT NULL,
	Descripcion VARCHAR(100),
	UUID UNIQUEIDENTIFIER DEFAULT NEWID() NOT NULL UNIQUE
)

CREATE TABLE Profesores(
	Id INT PRIMARY KEY IDENTITY(1,1),
	Nombre VARCHAR(50) NOT NULL,
	Apellido VARCHAR(50) NOT NULL,
	IdEscuela INT NOT NULL,
	UUID UNIQUEIDENTIFIER DEFAULT NEWID() NOT NULL UNIQUE
)

ALTER TABLE Profesores
ADD CONSTRAINT FK_Profesores_Escuelas 
FOREIGN KEY(IdEscuela)
REFERENCES Escuelas(Id)

CREATE TABLE Alumnos(
	Id INT PRIMARY KEY IDENTITY(1,1),
	Nombre VARCHAR(50) NOT NULL,
	Apellido VARCHAR(50) NOT NULL,
	FechaNacimiento DATETIME NOT NULL,
	IdEscuela INT NOT NULL,
	UUID UNIQUEIDENTIFIER DEFAULT NEWID() NOT NULL UNIQUE
)

ALTER TABLE Alumnos
ADD CONSTRAINT FK_Alumnos_Escuelas 
FOREIGN KEY(IdEscuela)
REFERENCES Escuelas(Id)

CREATE TABLE AlumnosXProfesores(
	Id INT PRIMARY KEY IDENTITY(1,1),
	IdProfesor INT NOT NULL,
	IdAlumno INT NOT NULL
)

ALTER TABLE AlumnosXProfesores
ADD CONSTRAINT FK_AlumnosXProfesores_Profesores
FOREIGN KEY(IdProfesor)
REFERENCES Profesores(Id)

ALTER TABLE AlumnosXProfesores
ADD CONSTRAINT FK_AlumnosXProfesores_Alumnos
FOREIGN KEY(IdAlumno)
REFERENCES Alumnos(Id)